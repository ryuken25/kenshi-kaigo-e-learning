// One-off script: precompute furigana (ruby-ready HTML) for every unique Japanese
// string used in the app, then write it as a static lookup map into
// src/furigana.generated.js. Runtime app never loads kuromoji — it just imports
// the precomputed map. Run manually: node scripts/gen-furigana.mjs
import KuroshiroImport from 'kuroshiro';
import KuromojiAnalyzerImport from 'kuroshiro-analyzer-kuromoji';
import { sections } from '../src/data.js';
import { writeFileSync } from 'node:fs';

const Kuroshiro = KuroshiroImport.default || KuroshiroImport;
const KuromojiAnalyzer = KuromojiAnalyzerImport.default || KuromojiAnalyzerImport;

const kuroshiro = new Kuroshiro();
await kuroshiro.init(new KuromojiAnalyzer());

const strings = new Set();
sections.forEach(s => {
  strings.add(s.titleJa);
  s.levels.forEach(l => {
    strings.add(l.titleJa);
    strings.add(l.objective);
    l.materi.forEach(m => strings.add(m.bodyJa));
    l.questions.forEach(q => {
      strings.add(q.questionJa);
      strings.add(q.explanationJa);
      q.choices.forEach(c => strings.add(c));
    });
  });
});

console.log(`Generating furigana for ${strings.size} unique strings...`);

const map = {};
let done = 0;
for (const text of strings) {
  if (!text) continue;
  try {
    const html = await kuroshiro.convert(text, { mode: 'furigana', to: 'hiragana' });
    map[text] = html;
  } catch (e) {
    map[text] = text;
  }
  done++;
  if (done % 100 === 0) console.log(`  ${done}/${strings.size}`);
}

const out = `// AUTO-GENERATED by scripts/gen-furigana.mjs — do not edit by hand.
// Maps: original Japanese string -> HTML string with <ruby><rt> furigana tags.
export const furiganaMap = ${JSON.stringify(map, null, 0)};
export const furigana = (text) => furiganaMap[text] || text;
`;

writeFileSync(new URL('../src/furigana.generated.js', import.meta.url), out);
console.log(`Done. Wrote ${Object.keys(map).length} entries to src/furigana.generated.js`);
